const RISK_PATTERNS = [
  /죽고\s*싶/,
  /자살/,
  /죽어\s*버리/,
  /사라지고\s*싶/,
  /없어지고\s*싶/,
  /살기\s*싫/,
  /살고\s*싶지\s*않/,
  /자해/,
  /칼로\s*긋/,
  /때려\s*맞았/,
  /맞고\s*있/,
  /학대/,
  /성폭력|성추행|몰카/,
  /괴롭힘을\s*당하/,
  /협박을?\s*받/,
];

export function detectRisk(text) {
  const t = String(text || "").replace(/\s+/g, " ");
  return RISK_PATTERNS.some((re) => re.test(t));
}

