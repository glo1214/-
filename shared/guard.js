/* ------------------------------------------------------------------
   지나친 해석 차단 (서버·클라이언트 공용)

   이 앱은 상담 도구도, 심리 검사 도구도 아니다.
   학생이 "조금 속상했다"고 적은 것을 두고 "자존감이 낮은 편이구나" 같은
   규정을 하는 순간, 이 앱은 해서는 안 되는 일을 하는 것이다.

   프롬프트로 금지하는 것만으로는 부족해서(모델은 지시를 어길 수 있다),
   생성된 문장을 여기서 한 번 더 걸러 낸다.
   걸리면 그 문장을 버리고 준비된 질문으로 넘어간다.
------------------------------------------------------------------ */

/* 1) 심리 규정·진단 어휘 */
const CLINICAL = [
  /자존감|자아\s?존중|열등감|우월감|자기\s?효능/,
  /트라우마|애착|방어\s?기제|회피형|내면\s?아이|상처받은/,
  /우울증|공황|강박|불안\s?장애|adhd|경계선|정신\s?건강|심리\s?상태/i,
  /진단|치료|상담\s?(을|이)\s?(받|필요)/,
];

/* 2) 사람을 규정하는 표현
   학생이 쓴 감정 단어를 되비추는 건 괜찮지만("'답답했다'고 했는데"),
   그 사람이 어떤 사람인지 단정하는 건 막는다. */
const LABELING = [
  /내향적|외향적|기질|성향(이|은|을|이라)/,
  /성격(이|은|을|상|적)/,
  /너는\s*[^.!?]{0,16}(사람|아이|타입|성격|편)(이|인|이야|이구나|인\s?것|같)/,
  /(예민|소심|무던|착|여린|강|약)한\s*(편|성격|아이|사람)/,
  /전형적(인|으로)|~형\s?인간/,
];

/* 3) 훈계·조언 (기획서 8.1 — 평가하거나 훈계하지 않는다)
   물음표가 붙은 문장은 질문이므로 여기서 걸리지 않게 서술형만 잡는다. */
const ADVICE = [
  /하는\s?게\s?좋(아|겠|을\s?거)/,
  /하면\s?좋을\s?거야|해\s?보는\s?걸\s?추천/,
  /그럴\s?땐|이럴\s?땐/,
  /중요한\s?건\s?[^.!?]{0,20}(야|다)\./,
];

/* 4) 답을 끼워 넣은 유도 질문
   이유를 '묻는' 것은 이 앱이 하려는 일이다. 막아야 하는 건
   AI 가 답을 정해 놓고 확인만 받는 질문이다.
     괜찮음: "왜 그 말이 마음에 남았을까?"
     막는다: "혹시 인정받고 싶었던 건 아닐까?" */
const LEADING = [
  /혹시\s[^.!?]{0,30}(아닐까|아니야|아닌가|였던\s?건\s?아)/,
  /거지\?/, // "~한 거지?", "~라고 느낀 거지?" — 확인만 받는 질문
  /(그래서|그러니까)\s[^.!?]{0,30}(구나|거구나|거네)/,
  /(라는|다는)\s?(뜻|의미|말)(이지|이구나|인\s?거지)/,
];

/**
 * 지나친 해석·규정·훈계·유도로 보이면 true.
 * 조금 과하게 잡히더라도 통과시키는 쪽보다 낫다 —
 * 걸러진 자리는 준비된 질문이 대신 채운다.
 */
export function looksInterpretive(text) {
  const t = String(text || "");
  if (!t) return false;

  // 사람을 규정하거나 진단하는 말은 질문이든 아니든 막는다
  if ([...CLINICAL, ...LABELING, ...LEADING].some((re) => re.test(t))) return true;

  // 조언은 서술문일 때만 막는다. ("그럴 땐 어떤 기분이었어?" 는 질문이므로 통과)
  return t
    .split(/(?<=[.!?…])\s+/)
    .filter((s) => s && !s.includes("?"))
    .some((s) => ADVICE.some((re) => re.test(s)));
}

/* 카드 항목처럼 짧은 문구를 걸러 낼 때 */
export function dropInterpretive(list) {
  if (!Array.isArray(list)) return [];
  return list.filter((item) => !looksInterpretive(item));
}

/* ------------------------------------------------------------------
   대화 길이 제한

   대화가 길어질수록 질문은 '무슨 일이 있었어?'에서 멀어지고
   '왜 그런 사람이 됐어?' 쪽으로 흐르기 쉽다.
   글쓰기 재료를 모으는 데는 이 정도면 충분하다.
------------------------------------------------------------------ */

export const CHAT_SOFT_LIMIT = 6; // 이쯤부터 "이제 정리해도 좋아"라고 권한다
export const CHAT_HARD_LIMIT = 10; // 더는 질문하지 않는다
